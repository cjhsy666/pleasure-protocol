// Look up vibration packet by b6 value
// Returns pointer to packet, or nullptr if not found
inline const uint8_t* vibrationGetPacket(uint8_t b6) {
    if (b6 == VIBRATION_IDLE_B6) {
        return VIBRATION_IDLE_PACKET;
    }
    for (size_t i = 0; i < VIBRATION_TABLE_SIZE; i++) {
        if (VIBRATION_TABLE[i].b6 == b6) {
            return VIBRATION_TABLE[i].packet;
        }
    }
    return nullptr;
}

// Convert slider position (1-100) to b6 value
inline uint8_t vibrationPositionToB6(int position) {
    if (position < 1) position = 1;
    if (position > 100) position = 100;
    return VIBRATION_BY_POSITION[position - 1];
}

// Get shock packet by level (0=off, 1=idle, 2-7=levels)
inline const uint8_t* shockGetPacket(uint8_t level) {
    if (level > 7) level = 7;
    return SHOCK_PACKETS[level];
}

